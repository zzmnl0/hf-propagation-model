function a4_c1w_pharlap_wgs84_ox(input_mat, output_dir, summary_json)
% Fixed-angle WGS84 O/X PHaRLAP behavior export for A4-C1W.

pharlap_root = 'D:\pharlap\pharlap_4.7.4';
addpath(fullfile(pharlap_root, 'mex'), '-begin');
addpath(genpath(fullfile(pharlap_root, 'src', 'matlab')), '-end');
in = load(input_mat);
assert(endsWith(lower(which('raytrace_3d')), '.mexw64'), ...
    'A4C1W:MexNotSelected', 'PHaRLAP raytrace_3d MEX was not selected');
if ~exist(output_dir, 'dir'), mkdir(output_dir); end

modes = [1, -1, 1, -1];
elevations = [22.0, 22.0, 39.5, 39.5];
case_ids = {'low_O', 'low_X', 'high_O', 'high_X'};
% PHaRLAP's documented highest-precision production profile. Tighter
% tolerances on gridded Ne/B fields can pin the solver at its minimum step
% until the 20000-point hard limit, which is not a converged ray.
tol = [1e-8, 0.01, 10.0];
records = repmat(struct('case_id', '', 'mode', 0, 'elevation_deg', NaN, ...
    'ray_label', -100, 'point_count', 0, 'csv', ''), 1, numel(case_ids));

for idx = 1:numel(case_ids)
    [ray_data, ~, state] = raytrace_3d( ...
        in.origin_lat_deg, in.origin_lon_deg, in.origin_height_km, ...
        elevations(idx), in.bearing_deg, in.frequency_MHz, modes(idx), ...
        1, tol, in.Ne_cm3, in.Ne_cm3, in.collision_Hz, ...
        in.iono_grid_parms, in.Bx_T, in.By_T, in.Bz_T, ...
        in.geomag_grid_parms);
    data = [state.pos_x(:), state.pos_y(:), state.pos_z(:), ...
        state.dir_x(:), state.dir_y(:), state.dir_z(:), ...
        state.group_path(:), state.geometrical_path(:), ...
        state.phase_path(:), state.indep_var(:), state.ODE_step_size(:)];
    csv_path = fullfile(output_dir, ['pharlap_' case_ids{idx} '.csv']);
    writematrix(data, csv_path);
    records(idx) = struct('case_id', case_ids{idx}, 'mode', modes(idx), ...
        'elevation_deg', elevations(idx), ...
        'ray_label', ray_data.ray_label(end), ...
        'point_count', size(data, 1), 'csv', csv_path);
end

summary = struct( ...
    'schema_version', 'a4-c1w-pharlap-wgs84-ox-v1', ...
    'status', 'completed_pharlap_wgs84_ox_export', ...
    'semantics', 'fixed_angle_same_WGS84_Ne_B_behavior_comparison', ...
    'pharlap_version', '4.7.4', ...
    'raytrace_path', which('raytrace_3d'), ...
    'matlab_release', version('-release'), ...
    'tol', tol, 'records', records);
fid = fopen(summary_json, 'w');
assert(fid >= 0, 'A4C1W:SummaryOpen', 'Cannot open summary JSON');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', jsonencode(summary, PrettyPrint=true));
clear cleanup raytrace_3d;
end
