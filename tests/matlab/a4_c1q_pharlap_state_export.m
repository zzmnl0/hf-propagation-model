function a4_c1q_pharlap_state_export(input_mat, output_dir, summary_json)
% Export strict fixed-angle PHaRLAP states for A4-C1Q; no root solving.

pharlap_root = 'D:\pharlap\pharlap_4.7.4';
addpath(fullfile(pharlap_root, 'mex'), '-begin');
addpath(genpath(fullfile(pharlap_root, 'src', 'matlab')), '-end');
case_ids = {'low_pharlap_anchor', 'low_ah3d_anchor', ...
    'high_pharlap_anchor', 'high_ah3d_anchor'};
branches = {'low_ray', 'low_ray', 'high_ray', 'high_ray'};
angles = [21.94290326504532, 21.94562872092976, ...
    39.54254824570964, 39.58701138438118];
tol = [1e-12, 0.001, 1];
result = struct('schema_version', 'a4-c1q-pharlap-state-export-v1', ...
    'status', 'blocked_c1q0_pharlap_export', ...
    'semantics', 'strict_fixed_angles_no_root_solving_pharlap_truth', ...
    'matlab_version', version, 'matlab_release', version('-release'), ...
    'pharlap_version', '4.7.4', 'raytrace_3d_sp_path', which('raytrace_3d_sp'), ...
    'tol', tol, 'angles_deg', angles, 'records', [], ...
    'error_identifier', '', 'error_message', '');

try
    in = load(input_mat);
    assert(strcmp(string(in.grid_variant), 'refined_1km') && ...
        in.frequency_MHz == 10 && in.OX_mode == 0 && in.nhops == 1, ...
        'A4C1Q:WrongInput', 'C1Q requires frozen 1 km B=0 Chapman input');
    assert(all(in.collision_freq_Hz(:) == 0) && in.earth_radius_m == 6371000, ...
        'A4C1Q:WrongPhysics', 'C1Q requires collision=0 and R=6371000 m');
    assert(endsWith(lower(result.raytrace_3d_sp_path), '.mexw64'), ...
        'A4C1Q:MexNotSelected', 'PHaRLAP MEX was not selected');
    if ~exist(output_dir, 'dir'), mkdir(output_dir); end
    records = repmat(struct('case_id', '', 'branch_id', '', ...
        'elevation_deg', NaN, 'raw_mat', '', 'ray_label', -100, ...
        'point_count', 0), 1, numel(case_ids));
    for idx = 1:numel(case_ids)
        [ray_data, ray_path_data, ray_state_vec] = raytrace_3d_sp( ...
            in.origin_lat_deg, in.origin_lon_deg, in.origin_height_km, ...
            angles(idx), 0.0, in.frequency_MHz, in.OX_mode, in.nhops, tol, ...
            in.earth_radius_m, in.iono_en_grid_cm3, in.iono_en_grid_5_cm3, ...
            in.collision_freq_Hz, in.iono_grid_parms, ...
            in.Bx_T, in.By_T, in.Bz_T, in.geomag_grid_parms);
        case_id = case_ids{idx}; %#ok<NASGU>
        branch_id = branches{idx}; %#ok<NASGU>
        elevation_deg = angles(idx); %#ok<NASGU>
        raw_mat = fullfile(output_dir, ['pharlap_' case_id '_strict_raw.mat']);
        save(raw_mat, 'ray_data', 'ray_path_data', 'ray_state_vec', ...
            'case_id', 'branch_id', 'elevation_deg', 'tol', '-v7.3');
        records(idx) = struct('case_id', case_id, 'branch_id', branch_id, ...
            'elevation_deg', elevation_deg, 'raw_mat', raw_mat, ...
            'ray_label', ray_data.ray_label(end), ...
            'point_count', numel(ray_path_data.lat));
    end
    result.records = records;
    result.status = 'completed_c1q0_strict_pharlap_state_export';
catch ME
    result.error_identifier = ME.identifier;
    result.error_message = ME.message;
end

fid = fopen(summary_json, 'w');
assert(fid >= 0, 'A4C1Q:SummaryOpen', 'Cannot open C1Q summary JSON');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', jsonencode(result, PrettyPrint=true));
clear cleanup raytrace_3d_sp;
if ~strcmp(result.status, 'completed_c1q0_strict_pharlap_state_export')
    error('A4C1Q:ExportFailed', '%s: %s', ...
        result.error_identifier, result.error_message);
end
end
